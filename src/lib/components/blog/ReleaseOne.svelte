<h2>Key Features</h2>
<p>
	Here are some of the features I’m most proud of, carefully designed to make studying easier and
	more effective:
</p>
<ul>
	<li>
		<strong>Starred card review:</strong> For
		<a href="https://quizlet.com/user/emmabrockman04/sets" rel="noopener noreferrer">Quizlet</a> enthusiasts,
		you can now star terms and focus on reviewing them. After a session, you can review starred terms
		or those you missed.
	</li>
	<li>
		<strong>Decks Tab:</strong>
		This tab allows you to view all cards from the current week. You can toggle between a flashcard view
		or a table of terms and definitions. The search bar is perfect for open-note quizzes, providing fast
		and precise results through partial or full searches.
	</li>
	<li>
